/** competiții de fotbal jucate de echipe naționale, nu de cluburi */
const CODURI_NATIONALE = new Set(["fifa.world", "uefa.euro", "uefa.nations", "fifa.friendly"]);

export function esteNationale(sport: string, codCompetitie: string): boolean {
  return sport === "fotbal" && CODURI_NATIONALE.has(codCompetitie);
}

